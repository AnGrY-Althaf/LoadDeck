// Self-contained HTML/CSV exports. The HTML report embeds Chart.js, the same renderer
// the app uses (public/js/report-view.js) and the run data, so it opens offline and can be
// emailed or attached to a ticket as a single file.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from './store.js';

const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

export function htmlReport(meta, report) {
  const chart = read('node_modules/chart.js/dist/chart.umd.min.js');
  const css = read('public/css/report.css');
  const view = read('public/js/report-view.js');
  const data = JSON.stringify({ meta, report }).replace(/</g, '\\u003c');
  const title = `${meta.name} — Load test report`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(title)}</title>
<style>
:root{--bg:#f6f7f9;--panel:#fff;--text:#1b1f24;--muted:#5d6672;--border:#e2e5ea;--accent:#6d4aff;--good:#1a7f45;--bad:#c62828;--warn:#b26a00;--grid:rgba(0,0,0,.07)}
@media (prefers-color-scheme: dark){:root{--bg:#0f1115;--panel:#171a21;--text:#e7e9ee;--muted:#9aa3b2;--border:#262b35;--accent:#9b85ff;--good:#3fbf74;--bad:#ff6b6b;--warn:#f0a83a;--grid:rgba(255,255,255,.08)}}
body{margin:0;background:var(--bg);color:var(--text);font:14px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif}
.standalone{max-width:1200px;margin:0 auto;padding:24px 16px 64px}
.standalone footer{color:var(--muted);font-size:12px;margin-top:32px;text-align:center}
${css}
</style>
</head>
<body>
<div class="standalone"><div id="report"></div><footer>Generated by LoadDeck · k6 · ${new Date().toISOString()}</footer></div>
<script>${chart}</script>
<script type="module">
${view}
const DATA = ${data};
renderReport(document.getElementById('report'), DATA.meta, DATA.report, { standalone: true });
</script>
</body>
</html>`;
}

export function csvReport(meta, report) {
  const rows = [['endpoint', 'method', 'group', 'requests', 'failed', 'error_rate', 'rps', 'avg_ms', 'min_ms', 'med_ms', 'p90_ms', 'p95_ms', 'p99_ms', 'max_ms']];
  for (const e of report.endpoints || []) {
    rows.push([e.name, e.method, e.group, e.count, e.fails, e.errRate.toFixed(4), e.rps.toFixed(2), ...['avg', 'min', 'med', 'p90', 'p95', 'p99', 'max'].map((k) => (+e[k]).toFixed(2))]);
  }
  rows.push([]);
  rows.push(['time', 'vus', 'requests_per_s', 'errors', 'avg_ms', 'p95_ms', 'p99_ms', 'iterations', 'bytes_received', 'bytes_sent']);
  for (const p of report.series || []) {
    rows.push([new Date(p.t * 1000).toISOString(), p.vus ?? '', p.rps, p.errors, p.avg?.toFixed(2) ?? '', p.p95?.toFixed(2) ?? '', p.p99?.toFixed(2) ?? '', p.iters, p.rx, p.tx]);
  }
  return rows.map((r) => r.map(csvCell).join(',')).join('\n');
}

function csvCell(v) {
  const s = String(v ?? '');
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
